source(file.path(dirname(sub("--file=", "", grep("--file=", commandArgs(), value = TRUE))), "common.R"))
library(zuhttp)
cl <- zu_client(http2 = "required", check = FALSE)
rq <- function(s, to = Inf) zu_req_timeout(zu_body_raw(zu_headers(zu_request("POST", paste0(URL, M)), "x-scn" = s, te = "trailers"), as.raw(c(0,0,0,0,0)), type = "application/grpc"), total = to)
cat("## raw zuhttp: timeout inside zu_resp_read, NO abort by caller\n")
r <- zu_perform(rq("h,w", 0.5), client = cl, stream = TRUE); show("read", zu_resp_read(r, 65536)); snew(0.4)
cat("## raw zuhttp: SIGINT inside zu_resp_read, NO abort by caller\n")
r <- zu_perform(rq("h,w"), client = cl, stream = TRUE); system(sprintf("(sleep 0.5; kill -INT %d) &", Sys.getpid())); show("read", zu_resp_read(r, 65536)); snew(0.4)
cat("## raw zuhttp: abort open response -> RST, reuse\n")
r <- zu_perform(rq("h,w"), client = cl, stream = TRUE); zu_resp_abort(r); show("abort twice", zu_resp_abort(r)); show("read after abort", zu_resp_read(r, 10)); show("trailers after abort", zu_resp_trailers(r))
invisible(zu_perform(rq("h,m1,t0"), client = cl)); snew(0.4)
