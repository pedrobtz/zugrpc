source(file.path(dirname(sub("--file=", "", grep("--file=", commandArgs(), value = TRUE))), "common.R"))
ch <- grpc_channel(URL)
sigint_in <- function(sec) system(sprintf("(sleep %s; kill -INT %d) &", sec, Sys.getpid()))
cat("## A: SIGINT during blocking stream read (1 message read, then stall)\n")
s <- scn(ch, "h,m1,w"); show("next", s$next_message())
sigint_in(0.5); r <- show("next (blocked)", s$next_message()); cat("   classes:", class(r$err %||% r$int), "\n"); state(s)
show("next again", s$next_message()); show("status", s$status()); print(ch); snew()
show("call after", grpc_call(ch, M, raw())$message); snew()
cat("## B: SIGINT during blocking unary call\n")
sigint_in(0.5); r <- show("call (blocked)", grpc_call(ch, M, raw(), metadata = c("x-scn" = "h,w"))); cat("   classes:", class(r$err %||% r$int), "\n"); snew()
show("call after", grpc_call(ch, M, raw())$message); snew()
cat("## C: SIGINT while waiting for stream headers (grpc_stream itself)\n")
sigint_in(0.5); r <- show("stream (blocked)", scn(ch, "s5000,h,m1,t0")); cat("   classes:", class(r$err %||% r$int), "\n"); print(ch); snew()
show("call after", grpc_call(ch, M, raw())$message); snew()
cat("## D: SIGINT mid-message: partial message pending, then rest arrives later; stream reusable?\n")
s <- scn(ch, "h,m1,p,w"); show("next", s$next_message())
sigint_in(0.5); r <- show("next (blocked)", s$next_message()); state(s); snew()
cat("## E: setTimeLimit(elapsed) during blocking stream read\n")
s <- scn(ch, "h,m1,s1500,m1,t0"); show("next", s$next_message())
r <- show("next (limit .5)", { setTimeLimit(elapsed = 0.5, transient = TRUE); on.exit(setTimeLimit()); s$next_message() }); setTimeLimit(); cat("   classes:", class(r$err %||% r$int), "\n"); state(s)
for (i in 1:3) show("next after", s$next_message()); state(s); snew()
cat("## F: setTimeLimit during unary\n")
r <- show("call (limit .5)", { setTimeLimit(elapsed = 0.5, transient = TRUE); grpc_call(ch, M, raw(), metadata = c("x-scn" = "h,s1500,m1,t0")) }); setTimeLimit(); cat("   classes:", class(r$err %||% r$int), "\n")
show("call after", grpc_call(ch, M, raw())$message); snew()
cat("## G: R.utils-style: interrupt between reads (no blocking) leaves stream usable\n")
s <- scn(ch, "h,m2,s800,m1,t0"); show("next", s$next_message())
r <- tryCatch({ sigint_in(0.2); Sys.sleep(2) }, interrupt = function(e) "interrupted in Sys.sleep")
print(r); for (i in 1:4) show("next", s$next_message()); state(s)
