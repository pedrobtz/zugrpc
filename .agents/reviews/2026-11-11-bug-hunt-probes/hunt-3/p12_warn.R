ch <- grpc_channel(URL)
wshow <- function(label, expr) withCallingHandlers(show(label, expr), warning = function(w) { cat("   [warning:", class(w)[1], substr(conditionMessage(w), 1, 70), "]\n"); invokeRestart("muffleWarning") })
cat("## A: baseline, warnings muffled: bad -bin trailer + status 5\n")
s <- scn(ch, "h,m1,T5"); for (i in 1:4) wshow(paste("next", i), s$next_message()); state(s)
cat("## B: caller wraps the read in tryCatch(warning=): status 5\n")
s <- scn(ch, "h,m1,T5"); for (i in 1:4) { r <- tryCatch(show(paste("next", i), s$next_message()), warning = function(w) cat("   caught warning ->", class(w)[1], "\n")) }
state(s); show("status", s$status()); show("trailers", s$trailers()); print(ch)
cat("## C: options(warn = 2): status 5\n")
op <- options(warn = 2); s <- scn(ch, "h,m1,T5"); for (i in 1:4) show(paste("next", i), s$next_message()); options(op); state(s); show("status", s$status())
cat("## D: options(warn = 2): status 0 with bad -bin trailer\n")
op <- options(warn = 2); s <- scn(ch, "h,m1,T0"); for (i in 1:4) show(paste("next", i), s$next_message()); options(op); state(s); show("status", s$status())
cat("## E: undecodable details, warn=2, status 5\n")
op <- options(warn = 2); s <- scn(ch, "h,m1,D5"); for (i in 1:4) show(paste("next", i), s$next_message()); options(op); state(s); show("status", s$status())
cat("## F: unary same, warn=2\n")
op <- options(warn = 2); show("call T5", grpc_call(ch, M, raw(), metadata = c("x-scn" = "h,m1,T5"))); show("call D5", grpc_call(ch, M, raw(), metadata = c("x-scn" = "h,m1,D5"))); options(op)
