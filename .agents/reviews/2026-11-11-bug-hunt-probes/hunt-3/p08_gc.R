for (i in 1:2000) { s <- scn(ch, "h,m1,t0"); while (!is.null(s$next_message())) {} }
cat("registry:", length(ls(ch$streams)), "next_id:", ch$next_id, "conns:", length(grep("OPEN", readLines(LOG))), "\n")
