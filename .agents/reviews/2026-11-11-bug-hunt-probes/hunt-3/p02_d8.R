source(file.path(dirname(sub("--file=", "", grep("--file=", commandArgs(), value = TRUE))), "common.R"))
ch <- grpc_channel(URL)
cat("## A: two streams open; server RSTs stream a; is b still alive, same conn?\n")
b <- scn(ch, "h,m1,s1500,m1,t0"); a <- scn(ch, "h,m2,x")
Sys.sleep(.3)
show("a next", a$next_message()); state(a)
show("b next", b$next_message()); show("b next", b$next_message()); show("b next", b$next_message()); state(b)
show("call", grpc_call(ch, M, raw())$message); snew()
cat("## B: raw zuhttp: server RST, no abort from us; next request same conn?\n")
cl <- zuhttp::zu_client(http2 = "required", check = FALSE)
rq <- function(s) zuhttp::zu_body_raw(zuhttp::zu_headers(zuhttp::zu_request("POST", paste0(URL, M)), "x-scn" = s, te = "trailers"), as.raw(c(0,0,0,0,0)), type = "application/grpc")
r <- zuhttp::zu_perform(rq("h,m2,x"), client = cl, stream = TRUE); Sys.sleep(.3)
show("read", zuhttp::zu_resp_read(r, 65536))
r2 <- zuhttp::zu_perform(rq("h,m1,t0"), client = cl); show("status", zuhttp::zu_resp_status(r2)); snew()
cat("## C: stream a fails protocol (we RST) while b open: b alive?\n")
b <- scn(ch, "h,m1,s1000,m1,t0"); a <- scn(ch, "h,b,w")
show("a next", a$next_message())
for (i in 1:3) show("b next", b$next_message()); snew()
cat("## D: cancel a while b open; b reads on; GC of dropped c while b open\n")
b <- scn(ch, "h,m1,s1000,m1,t0"); a <- scn(ch, "h,m1,w"); c0 <- scn(ch, "h,m1,w")
a$cancel(); rm(c0); invisible(gc()); print(ch)
for (i in 1:3) show("b next", b$next_message()); snew()
cat("## E: 50 streams on one channel, interleaved reads, cancel odd ones\n")
ss <- lapply(1:50, function(i) scn(ch, "h,m2,s200,m1,t0")); print(ch)
for (i in seq(1, 50, 2)) ss[[i]]$cancel()
ok <- vapply(seq(2, 50, 2), function(i) { n <- 0; while (!is.null(ss[[i]]$next_message())) n <- n + 1; n }, 0)
cat("messages per even stream:", unique(ok), " statuses:", unique(vapply(ss[seq(2,50,2)], function(s) s$status(), "")), "\n"); print(ch)
l <- snew(); cat("conns opened total:", length(grep("OPEN", readLines(LOG))), " RSTs in E:", length(grep("RST_STREAM", l)), "\n")
