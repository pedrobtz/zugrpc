source(file.path(dirname(sub("--file=", "", grep("--file=", commandArgs(), value = TRUE))), "common.R"))
library(parallel)
safe <- function(expr) tryCatch(expr, error = function(e) paste("ERR", paste(head(class(e), 2), collapse = ","), conditionMessage(e)))
ch <- grpc_channel(URL)
cat("## A: channel with an idle pooled connection; child calls twice, then parent calls\n")
show("parent call", grpc_call(ch, M, raw(), metadata = c("x-scn" = "h,m1,t0", "x-who" = "parent-before"))$message)
j <- mcparallel({ list(safe(grpc_call(ch, M, raw(), metadata = c("x-scn" = "h,m1,t0", "x-who" = "child-1"))$message), safe(grpc_call(ch, M, raw(), metadata = c("x-scn" = "h,m1,t0", "x-who2" = "child-2"))$message), Sys.getpid()) })
str(mccollect(j)[[1]])
show("parent call after child", grpc_call(ch, M, raw(), metadata = c("x-scn" = "h,m1,t0", "x-who3" = "parent-after"))$message)
show("parent call again", grpc_call(ch, M, raw())$message); snew()
cat("## B: mclapply 4 children each 3 calls on the inherited channel, parent after\n")
r <- mclapply(1:4, function(i) vapply(1:3, function(k) safe(as.character(as.integer(grpc_call(ch, M, raw())$message))), ""), mc.cores = 4); str(r)
show("parent after", grpc_call(ch, M, raw())$message); snew()
cat("## C: open stream (1 of 3 read, then more later); child reads it; parent reads after\n")
s <- scn(ch, "h,m3,s600,m3,t0"); show("parent next", s$next_message())
j <- mcparallel({ vapply(1:6, function(i) { m <- safe(s$next_message()); if (is.null(m)) "NULL" else paste(format(m), collapse = " ") }, "") }); print(mccollect(j)[[1]])
for (i in 1:7) show("parent next", s$next_message()); state(s); snew()
cat("## D: open stream; child cancels it; parent reads\n")
s <- scn(ch, "h,m1,s600,m1,t0"); j <- mcparallel({ s$cancel(); "child cancelled" }); print(mccollect(j)[[1]])
for (i in 1:3) show("parent next", s$next_message()); state(s); snew()
cat("## E: open stream; child calls grpc_close(ch); parent reads + calls\n")
s <- scn(ch, "h,m1,s600,m1,t0"); j <- mcparallel({ grpc_close(ch); "child closed" }); print(mccollect(j)[[1]])
for (i in 1:3) show("parent next", s$next_message()); show("parent call", grpc_call(ch, M, raw())$message); snew()
cat("## F: open stream untouched by child that just exits (and gc()s)\n")
s <- scn(ch, "h,m1,s600,m1,t0"); j <- mcparallel({ gc(); "child did nothing" }); print(mccollect(j)[[1]])
for (i in 1:3) show("parent next", s$next_message()); snew()
cat("## G: child drops its copy of the stream and gc()s\n")
s <- scn(ch, "h,m1,s600,m1,t0"); j <- mcparallel({ rm(s, envir = globalenv()); gc(); "child dropped" }); print(mccollect(j)[[1]])
for (i in 1:3) show("parent next", s$next_message()); snew()
