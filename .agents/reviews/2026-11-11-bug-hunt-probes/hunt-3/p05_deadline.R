source(file.path(dirname(sub("--file=", "", grep("--file=", commandArgs(), value = TRUE))), "common.R"))
ch <- grpc_channel(URL)
tm <- function(expr) { t0 <- Sys.time(); r <- expr; cat(sprintf("   [%.2fs]\n", as.numeric(Sys.time() - t0, units = "secs"))); invisible(r) }
cat("## A: stream, deadline 1s, server sends every 300ms forever-ish; loop\n")
s <- scn(ch, paste0("h,", paste(rep("m1,s300", 10), collapse = ","), ",t0"), deadline = 1)
tm(for (i in 1:8) show(paste("next", i), s$next_message())); state(s); snew()
cat("## A2: same with POSIXct\n")
s <- scn(ch, paste0("h,", paste(rep("m1,s300", 10), collapse = ","), ",t0"), deadline = Sys.time() + 1)
tm(for (i in 1:8) show(paste("next", i), s$next_message())); state(s); snew()
cat("## B: stall right after headers, deadline 1\n")
s <- scn(ch, "h,w", deadline = 1); tm(show("next", s$next_message())); show("next", s$next_message()); state(s); snew()
cat("## C: stall after 700ms, deadline 1 (design: fails by ~1.7s)\n")
s <- scn(ch, "h,s700,m1,w", deadline = 1); tm({show("next", s$next_message()); show("next", s$next_message())}); state(s); snew()
cat("## D: deadline passes while 3 messages buffered: delivered or dropped?\n")
s <- scn(ch, "h,m3,w", deadline = 0.5); show("next", s$next_message()); Sys.sleep(.7); for (i in 1:4) show(paste("next", i), s$next_message()); state(s); snew()
cat("## D2: deadline passes, body complete and buffered (server sent trailers)\n")
s <- scn(ch, "h,m3,t0", deadline = 0.5); show("next", s$next_message()); Sys.sleep(.7); for (i in 1:4) show(paste("next", i), s$next_message()); state(s); snew()
cat("## D3: unary: complete response within deadline\n")
show("call", grpc_call(ch, M, raw(), metadata = c("x-scn" = "h,m1,t0"), deadline = 0.5)$message)
cat("## E: headers never arrive, stream, deadline 0.5\n")
tm(show("stream", scn(ch, "s3000,h,m1,t0", deadline = 0.5))); print(ch); snew()
cat("## E2: unary stalls, deadline 0.5; then next call conn\n")
tm(show("call", grpc_call(ch, M, raw(), metadata = c("x-scn" = "h,w"), deadline = 0.5))); show("call", grpc_call(ch, M, raw())$message); snew()
cat("## F: numbers\n")
for (d in list(0, -1, NA, NA_real_, Inf, -Inf, NaN, 1e-12, 1e-4, 0.001, 2^31, 1e10, 1e300, 1L, TRUE, "1", c(1, 2), numeric(0),
               Sys.time() - 5, Sys.time() + 1e10, as.POSIXct(NA), Sys.time() + c(1, 2), Sys.Date() + 1, as.difftime(1, units = "mins"), as.POSIXlt(Sys.time() + 5), list(1))) {
  cat(sprintf("%-28s ", paste(deparse(d, width.cutoff = 30)[1], class(d)[1])))
  show("", grpc_call(ch, M, raw(), deadline = d)$message)
}
