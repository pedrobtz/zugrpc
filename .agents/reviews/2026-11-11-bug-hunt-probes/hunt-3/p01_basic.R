source(file.path(dirname(sub("--file=", "", grep("--file=", commandArgs(), value = TRUE))), "common.R"))
ch <- grpc_channel(URL)
cat("## unary\n"); show("call", grpc_call(ch, M, raw())$message); snew()
cat("## stream to end, use after end\n")
s <- scn(ch, "h,m3,t0"); for (i in 1:5) show(paste("next", i), s$next_message()); show("status", s$status()); show("trailers", names(s$trailers())); state(s)
show("cancel after end", s$cancel()); state(s); show("next", s$next_message()); snew()
cat("## cancel then read, cancel twice (3 buffered, 1 read)\n")
s <- scn(ch, "h,m3,w"); show("next", s$next_message()); state(s); show("cancel", s$cancel()); state(s); show("cancel2", s$cancel())
show("next", s$next_message()); show("next", s$next_message()); show("status", s$status()); show("trailers", s$trailers()); state(s); snew()
cat("## call after cancel: same conn?\n"); show("call", grpc_call(ch, M, raw())$message); snew()
cat("## non-OK status\n")
s <- scn(ch, "h,m2,t5"); for (i in 1:5) show(paste("next", i), s$next_message()); state(s); show("cancel", s$cancel()); state(s); snew()
cat("## Trailers-only-ish: status in trailers no messages\n")
s <- scn(ch, "h,t0"); show("next", s$next_message()); state(s)
cat("## two good messages + bad prefix in ONE data frame\n")
s <- scn(ch, "h,m2,b,w"); for (i in 1:5) show(paste("next", i), s$next_message()); state(s); snew()
cat("## good messages in one frame, bad in next (after 300ms)\n")
s <- scn(ch, "h,m2,s300,b,w"); for (i in 1:5) show(paste("next", i), s$next_message()); state(s); snew()
cat("## body ends inside message, same frame as two good ones\n")
s <- scn(ch, "h,m2,p,t0"); for (i in 1:5) show(paste("next", i), s$next_message()); state(s); show("status", s$status()); show("trailers", names(s$trailers())); snew()
cat("## server RST\n")
s <- scn(ch, "h,m2,x"); Sys.sleep(.3); for (i in 1:4) show(paste("next", i), s$next_message()); state(s); snew()
cat("## end without trailers\n")
s <- scn(ch, "h,m1,e"); for (i in 1:3) show(paste("next", i), s$next_message()); state(s); snew()
print(ch)
