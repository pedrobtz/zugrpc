source("<W>/hunt-2/common.R")
c1 <- ch(max_message = 100)
set_scen(M = list(h(H0), d(paste0(frs("hi"), "0000000065")), list(sleep = 300), h(list(c("x-t", "1"), c("grpc-status", "0")), TRUE)))
