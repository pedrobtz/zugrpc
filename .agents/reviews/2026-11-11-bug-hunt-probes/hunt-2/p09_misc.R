source("<W>/hunt-2/common.R")
M <- frs("hi"); M2 <- frs("yo")
gz <- function(x) { f <- tempfile(); con <- gzfile(f, "wb"); writeBin(x, con); close(con); readBin(f, "raw", 1e5) }
framed <- zugrpc:::frame_encode(charToRaw("hi"))
both("HTTP content-encoding: gzip, body = gzip(frame)", list(h(c(H0, list(c("content-encoding", "gzip")))), d(hx(gz(framed))), h(TOK, TRUE)))
both("HTTP content-encoding: gzip, body = plain frame", list(h(c(H0, list(c("content-encoding", "gzip")))), d(M), h(TOK, TRUE)))
both("content-encoding: identity", list(h(c(H0, list(c("content-encoding", "identity")))), d(M), h(TOK, TRUE)))
both("content-length mismatch (7 declared, 10 sent)", list(h(c(H0, list(c("content-length", "9")))), d(M), h(TOK, TRUE)))

cat("### deadline: server stalls after headers+1 msg\n")
set_scen(M = list(h(H0), d(M), list(sleep = 3000), d(M2), h(TOK, TRUE)))
c1 <- ch()
t0 <- Sys.time(); e <- tryCatch(grpc_call(c1, "/s.S/M", raw(), deadline = 0.5), error = function(e) e); cat(" unary:", class(e)[1:2], "after", round(as.numeric(Sys.time() - t0, units = "secs"), 2), "s parent", class(e$parent)[1], "\n")
Sys.sleep(0.2); cat("  wire:", tail(log_events(), 1), "\n")
t0 <- Sys.time(); st <- grpc_stream(c1, "/s.S/M", raw(), deadline = 0.5)
m1 <- st$next_message(); e <- tryCatch(st$next_message(), error = function(e) e); cat(" stream: first", rawToChar(m1), "then", class(e)[1:2], "after", round(as.numeric(Sys.time() - t0, units = "secs"), 2), "s; status()", deparse(st$status()), "grpc_status", e$grpc_status, "\n")
e2 <- tryCatch(st$next_message(), error = function(e) e); cat("  again:", class(e2)[1], identical(e, e2), "\n"); Sys.sleep(0.2); cat("  wire:", tail(log_events(), 1), "\n")
set_scen(M = list(h(H0), d(M), h(TOK, TRUE))); urun(c1, "/s.S/M"); cat("  conns ended since:", sum(grepl("conn end", log_events())), "\n")

cat("### cancel on the wire, then reuse same connection\n")
n0 <- sum(grepl("conn end", log_events()))
set_scen(M = list(h(H0), d(paste0(M, M2)), list(sleep = 2000), h(TOK, TRUE)))
st <- grpc_stream(c1, "/s.S/M", raw()); a <- st$next_message(); st$cancel(); st$cancel()
e <- tryCatch(st$next_message(), error = function(e) e); cat(" after cancel:", class(e)[1], "status()", deparse(st$status()), "trailers", deparse(st$trailers()), "\n")
Sys.sleep(0.2); cat("  wire:", tail(log_events(), 1), "\n")
set_scen(M = list(h(H0), d(M), h(TOK, TRUE))); urun(c1, "/s.S/M"); q <- last_req(); cat("  reuse stream id", q$stream, " conn ends since:", sum(grepl("conn end", log_events())) - n0, "\n")

cat("### early end by caller: stream not drained, close channel\n")
set_scen(M = list(h(H0), d(M), list(sleep = 500), d(M2), h(TOK, TRUE)))
st <- grpc_stream(c1, "/s.S/M", raw()); a <- st$next_message(); grpc_close(c1)
e <- tryCatch(st$next_message(), error = function(e) e); cat(" after close:", class(e)[1], "\n"); Sys.sleep(0.2); cat("  wire:", tail(log_events(), 2), "\n")

cat("### messages buffered when trailers carry an error, all in one burst\n")
both("3 msgs + status 13 burst", list(h(H0), d(paste0(M, M2, M)), h(list(c("grpc-status", "13"), c("grpc-message", "boom")), TRUE)))
both("2 msgs + trailing garbage 3 bytes + OK", list(h(H0), d(paste0(M, M2, "000000")), h(TOK, TRUE)))
both("2 msgs + trailing garbage + status 13", list(h(H0), d(paste0(M, M2, "000000")), h(list(c("grpc-status", "13")), TRUE)))
cat("### headers() before any read; non-OK trailers-only at open\n")
set_scen(M = list(h(c(H0, list(c("x-h", "1"), c("grpc-status", "7"), c("grpc-message", "denied"))), TRUE)))
c2 <- ch(); st <- tryCatch(grpc_stream(c2, "/s.S/M", raw()), error = function(e) e); cat(" open:", class(st)[1], " headers:", names(st$headers()), "status()", deparse(st$status()), "\n")
e <- tryCatch(st$next_message(), error = function(e) e); cat(" next:", class(e)[1], "e$headers", names(e$headers), "e$trailers", length(e$trailers), "status()", st$status(), "trailers()", deparse(st$trailers()), "\n")
e <- tryCatch(grpc_call(c2, "/s.S/M", raw()), error = function(e) e); cat(" unary: e$headers", names(e$headers), "e$trailers", names(e$trailers), "\n")
grpc_close(c2)
