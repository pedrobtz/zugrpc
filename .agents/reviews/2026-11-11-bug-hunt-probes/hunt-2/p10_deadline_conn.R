source("<W>/hunt-2/common.R")
M <- frs("hi"); M2 <- frs("yo")
ev <- function(n0) { l <- readLines(file.path(W, "req.log")); l <- l[-seq_len(n0)]; sub('"time":"[^"]*",', "", sub('"headers":.*', "...", l)) }
mark <- function() length(readLines(file.path(W, "req.log")))
set_scen(A = list(h(H0), d(M), list(sleep = 1500), d(M2), h(TOK, TRUE)),
         B = list(list(sleep = 3000), h(H0), d(M), h(TOK, TRUE)),
         C = list(h(H0), d(M), h(TOK, TRUE)))
c1 <- ch(); n0 <- mark()
cat("1) stream A open, unary B times out on the same channel, then keep reading A\n")
sa <- grpc_stream(c1, "/s.S/A", raw()); cat("  A first:", rawToChar(sa$next_message()), "\n")
e <- tryCatch(grpc_call(c1, "/s.S/B", raw(), deadline = 0.3), error = function(e) e); cat("  B:", class(e)[1], "\n")
r <- tryCatch(rawToChar(sa$next_message()), error = function(e) paste(class(e)[1], conditionMessage(e))); cat("  A second:", r, "\n")
Sys.sleep(0.3); print(ev(n0))
cat("2) stream B2 with deadline times out while stream A2 open\n"); n0 <- mark()
sa <- grpc_stream(c1, "/s.S/A", raw()); cat("  A first:", rawToChar(sa$next_message()), "\n")
sb <- tryCatch(grpc_stream(c1, "/s.S/B", raw(), deadline = 0.3), error = function(e) e); cat("  B open:", class(sb)[1], "\n")
r <- tryCatch(rawToChar(sa$next_message()), error = function(e) paste(class(e)[1], conditionMessage(e))); cat("  A second:", r, "\n")
Sys.sleep(0.3); print(ev(n0))
cat("3) stream with deadline that stalls after headers (read timeout) while A open\n"); n0 <- mark()
set_scen(A = list(h(H0), d(M), list(sleep = 1500), d(M2), h(TOK, TRUE)), D = list(h(H0), list(sleep = 3000), d(M), h(TOK, TRUE)))
sa <- grpc_stream(c1, "/s.S/A", raw()); cat("  A first:", rawToChar(sa$next_message()), "\n")
sd <- grpc_stream(c1, "/s.S/D", raw(), deadline = 0.3); e <- tryCatch(sd$next_message(), error = function(e) e); cat("  D next:", class(e)[1], class(e$parent)[1], "\n")
r <- tryCatch(rawToChar(sa$next_message()), error = function(e) paste(class(e)[1], conditionMessage(e))); cat("  A second:", r, "\n")
Sys.sleep(0.3); print(ev(n0))
grpc_close(c1)
