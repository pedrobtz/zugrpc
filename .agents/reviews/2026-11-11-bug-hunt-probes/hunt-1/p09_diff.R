resp <- function(status = 200L, headers = c("content-type" = "application/grpc"), body = as.raw(c(0,0,0,0,0)), trailers = c("grpc-status" = "0")) function(req) zuhttp::zu_response(status, headers = headers, body = body, trailers = trailers)
cmp <- function(label, r, ...) {
  m <- mock(respond = r, ...)
  u <- tryCatch(grpc_call(m$ch, M, raw()), error = identity)
  s <- tryCatch({ st <- grpc_stream(m$ch, M, raw()); o <- list(); while (!is.null(x <- st$next_message())) o <- c(o, list(x)); list(message = if (length(o) == 1) o[[1]] else o, headers = st$headers(), trailers = st$trailers(), status = st$status()) }, error = identity)
  norm <- function(x) { x <- unclass(x); x$call <- NULL; x[order(names(x))] }
  same <- identical(norm(u), norm(s)) && identical(class(u), class(s))
  cat("==", label, ": same =", same, "\n")
  if (!same) { cat("  unary : ", class(u)[1], "|", if (inherits(u, "condition")) conditionMessage(u), "\n"); cat("  stream: ", class(s)[1], "|", if (inherits(s, "condition")) conditionMessage(s), "\n")
    for (n in union(names(norm(u)), names(norm(s)))) if (!identical(norm(u)[[n]], norm(s)[[n]])) { cat("   field", n, ":\n"); str(norm(u)[[n]]); str(norm(s)[[n]]) } }
  invisible(list(u = u, s = s))
}
