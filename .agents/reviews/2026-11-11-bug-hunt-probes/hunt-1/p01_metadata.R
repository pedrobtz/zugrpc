show <- function(label, md, ch_headers = NULL) {
  cat("==", label, "\n")
  m <- try_(mock(headers = ch_headers)); if (inherits(m, "caught")) { print(m); return(invisible()) }
  r <- try_(grpc_call(m$ch, M, raw(), metadata = md))
  if (inherits(r, "caught")) { print(r) }
  if (length(m$seen$requests)) { h <- sent(m)$headers; print(h) } else cat("  (nothing sent)\n")
}
