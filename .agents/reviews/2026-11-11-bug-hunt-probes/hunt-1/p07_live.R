go <- function(label, ..., headers = NULL, stream = FALSE, url_ = url, ch = NULL, max_message = 128 * 1024^2) {
  cat("==", label, "\n"); own <- is.null(ch)
  if (own) { ch <- try_(grpc_channel(url_, headers = headers, max_message = max_message)); if (inherits(ch, "caught")) return(print(ch)) }
  if (own) on.exit(grpc_close(ch))
  t0 <- Sys.time()
  r <- try_(if (stream) { st <- grpc_stream(ch, M, raw(), ...); st$next_message() } else grpc_call(ch, M, raw(), ...)$message)
  if (inherits(r, "caught")) { print(r); cat("   after", format(Sys.time() - t0), "\n"); return(invisible()) }
  j <- jsonlite::fromJSON(rawToChar(r)); md <- j$md
  if (grepl("60k", label)) return(invisible(j)); for (n in setdiff(names(md), c("accept", "content-type", "grpc-accept-encoding", if (!grepl("content-length|accept-encoding", label)) c("accept-encoding", "content-length"), if (!grepl("ua|baseline|upper", label)) c("user-agent", ":authority")))) cat("  ", n, "=", paste(encodeString(md[[n]], quote = '"'), collapse = " | "), "\n")
  if (!is.null(j$deadline_left)) cat("   deadline_left =", j$deadline_left, "\n")
  invisible(j)
}
